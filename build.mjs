/**
 * Assemble `client.js` from `src/`.
 *
 * The browser module graph loads exactly one bundle per package (`dsh.client`
 * has a single `./client` export), so the shipped plugin has to be one
 * self-contained file. The sources stay separate and readable, each one wrapped
 * by this script into a tiny CommonJS-ish registry the generated factory
 * evaluates in dependency order.
 *
 *   node build.mjs        (write client.js)
 *   node build.mjs --check (report drift without writing)
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE = "dsh-coding-sound";
const TARGET = join(HERE, "client.js");

/** Load order; every entry declares its dependencies by module id. */
const MODULES = [
  { file: "src/presets.js", dir: "presets", deps: [] },
  { file: "src/settings.js", dir: "settings", deps: ["presets"] },
  { file: "src/chimes.js", dir: "chimes", deps: ["settings"] },
  { file: "src/engine.js", dir: "engine", deps: ["presets"] },
  { file: "src/observer.js", dir: "observer", deps: [] },
  { file: "src/sessions.js", dir: "sessions", deps: ["settings"] },
  { file: "src/client.js", dir: "client", deps: ["presets", "settings", "chimes", "engine", "observer", "sessions"] },
];

/** Dependencies are injected as parameters, so no source file calls require() for them. */
const PARAM_NAMES = ["presets", "settings", "chimes", "engine", "observer", "sessions"];

/** The load marker test.mjs greps for; kept byte-stable on purpose. */
const LOAD_LINE = `    return registry.load("client");`;

function loadSource(relativePath) {
  return readFileSync(join(HERE, relativePath), "utf8").replace(/\r\n/g, "\n").trimEnd();
}

function assembleRegistry() {
  return [
    `    /* Generated by build.mjs; see src/. Modules evaluate in dependency order. */`,
    `    const factories = new Map();`,
    `    const cache = new Map();`,
    `    /* Platform modules (react, …) resolve through the loader's own require, which`,
    `       arrives as this factory's first argument. */`,
    `    const request = (specifier) => {`,
    `      if (typeof loaderRequire === "function") return loaderRequire(specifier);`,
    `      const testSeam = globalThis.__DCS_REQUIRE__;`,
    `      if (typeof testSeam === "function") return testSeam(specifier);`,
    `      throw new Error("coding-sound: no loader for module " + specifier);`,
    `    };`,
    `    const registry = {`,
    `      define(id, dependencies, factory) {`,
    `        factories.set(id, { dependencies, factory });`,
    `      },`,
    `      load(id) {`,
    `        if (cache.has(id)) return cache.get(id);`,
    `        const entry = factories.get(id);`,
    `        if (entry === undefined) throw new Error("coding-sound: nothing defines module " + id);`,
    `        const module = { exports: {} };`,
    `        const dependencies = entry.dependencies.map((dependency) => registry.load(dependency));`,
    `        entry.factory(module, module.exports, request, ...dependencies);`,
    `        cache.set(id, module.exports);`,
    `        return module.exports;`,
    `      },`,
    `    };`,
  ].join("\n");
}

function assemble() {
  const parts = [];
  parts.push(`/**
 * GENERATED FILE — edit src/*.js and run \`node build.mjs\`.
 *
 * One bundle because the browser module graph loads a single \`./client\`
 * artifact per package. Inside the factory the sources are evaluated in
 * dependency order against a tiny CommonJS-ish registry, so they keep normal
 * module semantics.
 */
window.__ModuleLoader__.load({
  id: "${PACKAGE}",
  factory(loaderRequire) {
`);
  parts.push(assembleRegistry());
  parts.push("");

  for (const entry of MODULES) {
    const source = loadSource(entry.file)
      .split("\n")
      .map((line) => (line.length === 0 ? "" : `        ${line}`))
      .join("\n");
    const params = PARAM_NAMES.filter((name) => entry.deps.includes(name));
    parts.push(`    //#region ${entry.file}`);
    parts.push(
      `    registry.define(${JSON.stringify(entry.dir)}, [${entry.deps.map((dep) => JSON.stringify(dep)).join(", ")}], function (module, exports, require${params.length > 0 ? `, ${params.join(", ")}` : ""}) {`,
    );
    parts.push(source);
    parts.push("    });");
    parts.push(`    //#endregion ${entry.file}`);
    parts.push("");
  }

  parts.push(`
    try {
${LOAD_LINE}
    } catch (error) {
      /* Every declared client module sits in an initial boot batch, so letting
         this escape would blank the whole page over a cosmetic audio plugin.
         Stay a plugin failure: no Settings section, and the reason on the
         console. */
      if (typeof console !== "undefined" && typeof console.error === "function") {
        console.error("[coding-sound] client module failed to load; Settings stays unchanged", error);
      }
      return { name: "coding-sound", apply() {} };
    }
  }
});
`);
  return parts.join("\n");
}

/** Imported by test.mjs, which compares the artifact against this output. */
export { assemble, LOAD_LINE, TARGET as target };

const invokedDirectly = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  const expected = assemble();
  if (process.argv.includes("--check")) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== expected) {
      console.error("build: client.js is stale; run `node build.mjs`");
      process.exitCode = 1;
    } else {
      console.log("build: client.js is up to date");
    }
  } else {
    mkdirSync(HERE, { recursive: true });
    writeFileSync(TARGET, expected, "utf8");
    console.log(`build: wrote client.js (${expected.length} bytes)`);
  }
}
